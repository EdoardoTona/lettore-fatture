#!/usr/bin/env python3
"""Offline bridge integration check. Does not print document content."""
import json
import re
from pathlib import Path
import subprocess
import sys
import tempfile
import time

root = Path(__file__).resolve().parents[2]
app = Path(sys.argv[1]) if len(sys.argv) > 1 else root / "artifacts/macos/Lettore Fatture.app"
worker = app if app.is_file() else app / "Contents/Resources/bridge/fatture"
output = root / "artifacts/verification"
output.mkdir(parents=True, exist_ok=True)
process = subprocess.Popen([str(worker), "bridge"], stdin=subprocess.PIPE, stdout=subprocess.PIPE, text=True)


def request(payload):
    process.stdin.write(json.dumps(payload) + "\n")
    process.stdin.flush()
    line = process.stdout.readline()
    assert line, "Il bridge si è interrotto"
    result = json.loads(line)
    assert result["id"] == payload["id"]
    return result


try:
    assert request({"id": "ping", "operation": "ping"})["ok"]
    with tempfile.TemporaryDirectory() as directory:
        invalid = Path(directory) / "invalid.xml"
        invalid.write_text("<receipt/>")
        assert not request({"id": "invalid", "operation": "open", "path": str(invalid), "outputDirectory": directory})["ok"]
        assert request({"id": "after-error", "operation": "ping"})["ok"]
    elapsed = []
    total = 0
    documents = []
    files = sorted(p for p in (root / "esempi").iterdir() if p.suffix in {".xml", ".p7m", ".eml"})
    assert files, "Mancano i documenti di esempio"
    for index, file in enumerate(files):
        destination = output / str(index)
        # Clean only PDFs generated by earlier runs of this check, identified
        # by the engine's random identifier; leave other local files alone.
        if destination.exists():
            for stale in destination.glob("*.pdf"):
                if re.fullmatch(r"[0-9a-f]{32}\.pdf", stale.name):
                    stale.unlink()
        start = time.perf_counter()
        result = request({"id": str(index), "operation": "open", "path": str(file), "outputDirectory": str(destination)})
        elapsed.append((time.perf_counter() - start) * 1000)
        assert result["ok"], result.get("error")
        value = result["result"]
        documents.extend(value["documents"])
        assert value["documents"], "Nessun documento generato"
        assert not value["warnings"], value["warnings"]
        for doc in value["documents"]:
            pdf = Path(doc["pdfPath"])
            assert pdf.is_file() and pdf.read_bytes().startswith(b"%PDF-")
            assert pdf.resolve().is_relative_to(output.resolve())
            total += 1
    print(f"Bridge pubblicato: {len(files)} file aperti, {total} documenti, nessun errore")
    print(f"Apertura + PDF: prima {elapsed[0]:.0f} ms, mediana {sorted(elapsed)[len(elapsed)//2]:.0f} ms, massimo {max(elapsed):.0f} ms")
    export = request({"id": "excel", "operation": "exportExcel", "documents": documents,
                      "exportPath": str(root / "artifacts/fatture-esempi.xlsx")})
    assert export["ok"], export.get("error")
    invoices = [document for document in documents if document.get("invoice")]
    unique = len({document["invoice"]["fingerprint"] for document in invoices})
    assert export["export"]["invoiceCount"] == unique
    assert export["export"]["duplicateCount"] == len(invoices) - unique
    print(f"Excel: {unique} fatture, {len(invoices) - unique} duplicati esclusi, {len(documents) - len(invoices)} documenti non fattura ignorati")
finally:
    process.stdin.close()
    process.wait(timeout=10)
    assert process.returncode == 0
